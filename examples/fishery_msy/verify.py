"""验证钩子（案例：渔业最大可持续产量 MSY）。

同一套引擎、同一套检查器——这里只做"把可检查的对象交出去"这件事。
注意钩子里没有一处提到照明、灯杆、库存、报童、信贷：领域知识全在本文件，**引擎不需要知道**。

本案例的结论类型覆盖了：全称断言 / 最优性 / 口径相关 / 极限 ——
与案例 A（统计量/等式/极值）、案例 B（全称断言/极值/覆盖/稳健性/口径/极限）、
案例 C（全称断言/口径/极值）组合各不相同，但走的是同一张 `REQUIRED_BY_KIND` 表。

本案例独有的"窄带陷阱"成因：**局部额外死亡带**（某细分产卵渔场在特定努力档位附近的
集中减员），和案例 B 的"几何缺口"、案例 C 的"统计越界带"是三种**不同**的失败机理，
所以三个案例各自教会引擎一件不同的事。
"""
from __future__ import annotations

import solve

# ------------------------------------------------------------
# P2 全称断言①（有效口径）：∀E ∈ [0, 300]，有效产卵生物量 ≥ B_MIN
#   约定 margin(E) > 0 表示该档位违反保护（有效生物量低于下限）
#   —— 这条会被"局部额外死亡带"在 E≈183 处打破，而粗网格整段跳过它
# ------------------------------------------------------------


def stock_margin(E):
    """有效口径下：B_MIN − 有效产卵生物量。>0 = 违反保护（窄带陷阱的目标）。"""
    return solve.stock_margin(E)


# ------------------------------------------------------------
# P2 全称断言②（标称口径）：∀E ∈ [0, 300]，标称平衡生物量 ≥ B_MIN
#   标称口径**不计**局部额外死亡，所以它全程成立——与①形成对照
# ------------------------------------------------------------
def nominal_stock_margin(E):
    """标称口径下：B_MIN − 标称平衡生物量。>0 = 标称口径下违反保护。"""
    return solve.nominal_margin(E)


def flip_nominal_stock(E):
    """P5 翻转判据（标称口径）：标称生物量 − B_MIN；>0 = 高于下限（安全侧）。

    在 [0, 300] 上标称生物量单调下降，最小值 250 吨仍高于下限 240，
    所以**不存在翻转边界**——P5 会如实回报"未找到"，这正是标称口径"看似安全"的原因。
    """
    return solve.x_star(E) - solve.B_MIN


# ------------------------------------------------------------
# P1 双路径：MSY 的两条独立实现（解析式 vs 细步扫描）
# ------------------------------------------------------------
def y_max_analytic():
    """路径A：闭式 rK/4。"""
    return solve.y_max_analytic()


def y_max_numeric():
    """路径B：完全不用解析式，在 [0, r/q] 上细扫求产量最大值（返回标量）。"""
    return solve.y_max_numeric()[0]


# ------------------------------------------------------------
# P3 连续复核：把"努力度"当连续变量检验产量是否在 E* 处真取最大
# ------------------------------------------------------------
def neg_yield(t):
    """目标函数：取负的产量（把"最大化产量"变成"最大化 −产量"）。

    若 E*=200 真是全局最大，任何偏离都应使产量下降；P3 的对抗搜索会确认
    峰值就在 E* 处、且给出平台宽度（用于如实报告"有多平"）。
    """
    return -solve.yield_at(t)


# ------------------------------------------------------------
# P5 翻转边界：产量对努力的导数符号翻转点 = MSY 努力度 E*
# ------------------------------------------------------------
def flip_yield(E):
    """产量的翻转判据：给定努力 E，产量导数符号。零点即 MSY 努力度。

    g(E) = qK(1 − 2qE/r)：E<E* 时为正（增产），E>E* 时为负（过捕减产）。
    """
    return solve.flip_yield(E)


# ------------------------------------------------------------
# P4 极限与量纲
# ------------------------------------------------------------
def limit_samples():
    """① 努力度→0：不捕捞，产量→0；② 努力度→r/q（=400）：生物量崩溃→0；
       ③ 努力度=E*：产量恰为闭式最大值 rK/4。"""
    return [
        (0.0, solve.yield_at(0.0), 0.0),
        (400.0, solve.x_star(400.0), 0.0),
        (solve.R / (2.0 * solve.Q), solve.yield_at(solve.R / (2.0 * solve.Q)),
         solve.R * solve.K / 4.0),
    ]


# ------------------------------------------------------------
# P6 口径
# ------------------------------------------------------------
def caliber_eff_vs_nom():
    """口径对照：同一物理对象（产卵生物量）在两种口径下的数值完全不同。

    这一组数字**故意**来自两套口径，所以必须各自标口径、并列报出、不许相减。
    """
    return [
        {"label": "E=%g 处有效产卵生物量" % solve.E_SPIKE,
         "value": solve.effective(solve.E_SPIKE),
         "caliber": "有效口径：标称平衡生物量 − 局部额外死亡带"},
        {"label": "E=%g 处标称平衡生物量" % solve.E_SPIKE,
         "value": solve.x_star(solve.E_SPIKE),
         "caliber": "标称口径：按 Schaefer 平衡式 x*=K(1−qE/r)，不计局部额外死亡"},
    ]
